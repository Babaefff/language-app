/** The "You can now…" line for a lesson; word sets get a line about the words they add. */
export function canDoFor(unit: { id: string; words: unknown[] }, langName: string): string {
  return CAN_DO[unit.id] ?? `recognise and use ${unit.words.length} more everyday ${langName} words`;
}

/** True for topic lessons (word sets have no written statement). */
export const hasCanDo = (id: string) => id in CAN_DO;
