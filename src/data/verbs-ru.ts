import type { Level } from './types';

/**
 * Russian verb definition. The present (or, for perfective verbs, the simple future) is given in
 * full: я, ты, он/она, мы, вы, они. The past, future and conditional are built by rule.
 */
export interface VerbRu {
  inf: string;
  en: string;
  level: Level;
  /** Imperfective (ongoing / repeated) or perfective (one completed action). */
  aspect: 'impf' | 'pf';
  /** The other verb of the aspect pair, if the course has it. */
  pair?: string;
  /** Present (imperfective) or simple future (perfective): я, ты, он, мы, вы, они. */
  pres: string[];
  /** Past [он, она, оно, они] when it isn't the infinitive stem + л / ла / ло / ли. */
  past?: string[];
  /** Imperative [ты, вы] when it isn't the regular one. */
  imp?: (string | null)[];
}

const v = (inf: string, en: string, level: Level, aspect: 'impf' | 'pf', pres: string, extra: Partial<VerbRu> = {}): VerbRu =>
  ({ inf, en, level, aspect, pres: pres.split(' '), ...extra });

