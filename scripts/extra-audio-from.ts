/**
 * Adds every speakable text of a personal-material file (words, examples, sentences, test
 * answers, note examples) to scripts/extra-audio/<lang>.txt, so the next deploy (or
 * `npm run audio:<lang>`) records natural-voice clips for them.
 *
 *   npm run audio:extra -- path/to/material.json
 *
 * Only the texts are kept (no names, emails, tab names or titles).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) { console.error('Usage: npm run audio:extra -- path/to/material.json'); process.exit(1); }
type Q = { type: string; q: string; options?: string[]; answer: number | string; accept?: string[] };
const m = JSON.parse(readFileSync(file, 'utf8')) as {
  lang: string;
  lessons?: { words: string[][]; sentences?: string[][]; notes?: string }[];
  tests?: { questions: Q[] }[];
};
const out = new Set<string>();
/** Notes mix English explanations with examples: keep only the examples. */
const EN = new Set('the a an you i me my to is it that this of and or for imagine literally means always never with not'.split(' '));
const looksEnglish = (t: string) => /[—·→]/.test(t) || (t.toLowerCase().match(/[a-zäöüß']+/g) ?? []).some((w) => EN.has(w));
const add = (t?: string) => { const x = t?.replace(/\*\*/g, '').trim(); if (x) out.add(x); };
for (const l of m.lessons ?? []) {
  for (const [w, , ex] of l.words) { add(w); add(ex); }
  for (const [s] of l.sentences ?? []) add(s);
  // Italic examples in the notes (*Ich habe gezeichnet.*) and table cells with foreign words.
  for (const x of (l.notes ?? '').matchAll(/(?<!\*)\*([^*\n]+)\*(?!\*)/g)) if (!looksEnglish(x[1])) add(x[1]);
}
for (const t of m.tests ?? []) for (const q of t.questions) {
  if (q.type === 'choice' && typeof q.answer === 'number') {
    const right = q.options?.[q.answer];
    if (q.q.includes('___') && right) add(q.q.replace(/_{2,}/, right));
    else if (right && !/^[A-Za-z' ]+$/.test(right)) add(right);
  } else if (typeof q.answer === 'string') add(q.answer);
}
const target = new URL(`./extra-audio/${m.lang}.txt`, import.meta.url).pathname;
const before = existsSync(target) ? readFileSync(target, 'utf8').split('\n').map((x) => x.trim()).filter(Boolean) : ['# Extra texts to record (one per line). Generated by scripts/extra-audio-from.ts.'];
const known = new Set(before);
const added = [...out].filter((t) => !known.has(t));
writeFileSync(target, [...before, ...added].join('\n') + '\n');
console.log(`${added.length} new texts added to scripts/extra-audio/${m.lang}.txt (${before.length + added.length - 1} in total).`);
